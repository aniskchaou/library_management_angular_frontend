export const TRANSLATIONS: Record<AppLang, MenuI18nDict> = { EN, VI };

@Injectable({ providedIn: 'root' })
export class TranslationService {

  private _lang = new BehaviorSubject<AppLang>(
    (localStorage.getItem(STORAGE_KEY) as AppLang) || 'EN'
  );

  /** Emits the current language code ('EN' | 'VI'). */
  currentLang$ = this._lang.asObservable();

  get currentLang(): AppLang { return this._lang.value; }

  constructor(private httpService: HTTPService) {
    // Push initial translations so menuI18n bindings work on startup.
    this.httpService.menuI18n.next(TRANSLATIONS[this._lang.value]);
  }

  /**
   * Switch the active language.
   * Persists the choice and pushes new menuI18n translations to all subscribers.
   */
  setLang(lang: AppLang): void {
    localStorage.setItem(STORAGE_KEY, lang);
    this._lang.next(lang);
    this.httpService.menuI18n.next(TRANSLATIONS[lang]);
  }

  /** Return the translation for a dot-notation key, e.g. 'ui.save'. */
  translate(key: string): string {
    return TRANSLATIONS[this._lang.value][key] ?? key;
  }
}
